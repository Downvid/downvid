import {
  classifyParseError,
  isTemplateOnlyReport,
  NO_ISSUE_KINDS,
  type ParseErrorKind,
} from '../../shared/parse-error'

/**
 * Issue 质量分类：判断一条新开的 Issue 该不该被自动关闭。
 *
 * 与 `.github/workflows/triage.yml` 共用（workflow 通过 `ts.transpileModule`
 * 加载本文件，因此这里是**唯一实现**，界面、CI 校验、自动关闭三处标准一致）。
 *
 * ## 为什么需要自动关闭
 *
 * 应用内的「提交 Issue」会**预填**一条只有错误类别、没有用户输入的正文，
 * 用户一路回车就能开出 `[Bug] 该视频需要登录或访问权限，请检查 Cookies 设置`
 * 这种 Issue —— 里面没有任何可行动的信息（实测同一文案连开两条 #58 #59）。
 * 项目越火这类报告越多，真正的报告会被淹没。
 *
 * ## 判据（两类，都要能给出**可行动**的回复）
 *
 * 1. **空报告**：正文剥掉应用模板后没有任何用户内容
 * 2. **自助类**：错误类别属于 `NO_ISSUE_KINDS`（配 Cookie、换链接、等限流……）
 *    且正文里没有代码块（没有原始报错就无从判断是不是真的回归）
 *
 * 拿不准时一律**不关**——错关一条真实报告比留一条噪音更糟。
 */

export interface TriageVerdict {
  close: boolean
  /** 关闭原因（用于日志与测试断言） */
  reason: 'template-only' | 'self-service' | 'ok'
  /** 关评里用的模板键，见 commentFor() */
  comment: 'template' | 'selfService' | 'none'
  /** 分类出的解析错误类别（可能为 undefined） */
  kind?: ParseErrorKind
}

/**
 * 分类一条 Issue。
 *
 * 判定**顺序有讲究**：自助类优先于「空报告」。
 *
 * 因为对 #58 这种「正文里只有 authentication 文案」的报告，最有用的回复是
 * 「这样配 Cookie」——用户的真实问题就是没配 Cookie。若先按「空报告」判，
 * 他收到的会是「你什么都没写」，对他毫无帮助。
 *
 * `body` 用原始 Markdown（含代码块）。`labels` 可选，用于识别模板。
 */
export function classifyIssue(body: string): TriageVerdict {
  const text = body || ''
  const kind = classifyParseError(text)

  // 正文里有没有「原始报错」——代码块是应用回显 yt-dlp 输出的唯一位置。
  // 有它就说明用户至少拿到了真实错误，值得人工看一眼。
  const hasCodeBlock = /```[\s\S]*?```/.test(text)
  const hasUrl = /https?:\/\/\S+/.test(text)
  const hasRawEvidence = hasCodeBlock || hasUrl

  // 1) 自助类：用户自己能解决，且没有原始报错可看 → 关闭并给可行动的步骤。
  //    有代码块/链接时放行：那可能是真的回归（历史 #50 的 page-reload 就是这样）。
  if (!hasRawEvidence && kind !== 'unknown' && NO_ISSUE_KINDS.includes(kind)) {
    return { close: true, reason: 'self-service', comment: 'selfService', kind }
  }

  // 2) 空报告：正文剥掉应用模板后没有任何用户内容，且不是上面能给出指引的类别
  if (isTemplateOnlyReport(text)) {
    return { close: true, reason: 'template-only', comment: 'template', kind }
  }

  // 3) 其余放行——错关一条真实报告比留一条噪音更糟
  return { close: false, reason: 'ok', comment: 'none', kind }
}

/**
 * 自动关闭时回复的正文（中英双语，仓库有海外用户）。
 *
 * ## 关于 `@` 提及
 *
 * 文案里刻意**不出现任何 `@用户名` 或 `#编号`**：GitHub 会把它们变成
 * 通知与交叉引用，一条自动回复就可能去打扰无关的人。
 * `scripts/test-issue-triage.mjs` 用断言钉住了这一点。
 */
export function commentFor(verdict: TriageVerdict): string {
  if (verdict.comment === 'template') {
    return [
      '这条 Issue 看起来是应用内「提交 Issue」按钮**自动生成**的，正文里没有包含任何你的输入，',
      '因此无法据此定位问题，先自动关闭了。',
      '',
      '如果确实遇到了问题，请重新提交并补充：**你下载的是哪个链接**、**界面上完整显示了什么**。',
      '正文里的代码块（原始报错）是最有价值的部分，请一并保留。',
      '',
      '---',
      '',
      'This issue looks like it was auto-generated by the in-app "Report an issue" button with no',
      'input from you, so there is nothing to act on. Closing it for now.',
      '',
      'If you did hit a problem, please reopen with **the link you tried** and **the full message you saw**.',
    ].join('\n')
  }

  if (verdict.comment === 'selfService') {
    return [
      '这类提示通常**不需要改代码**，按下面处理即可，先自动关闭了：',
      '',
      selfServiceHint(verdict.kind),
      '',
      '如果按上面的步骤做过之后仍然失败，请重新提交，并**带上完整报错**——那说明可能是真的回归，我们会看。',
      '',
      '---',
      '',
      'This usually needs a setting change rather than a code fix, so it is closed automatically.',
      'If it still fails after the steps above, please reopen **with the full error output**.',
    ].join('\n')
  }

  return ''
}

/**
 * 该 Issue 是否是「解析/下载失败」类报告。
 *
 * 用途：批量分类时给这类打 `parse-error` 标签，方便按平台筛选。
 * 只看标题与正文里的**报告形态**（`[Bug] 解析失败` / `[解析]`），
 * 不依赖错误类别是否被识别——`no such table: meta` 这类 yt-dlp 内部报错
 * 目前归不到具体类别（kind=unknown），但它显然仍是解析失败报告。
 */
export function isParseIssue(title: string, body: string): boolean {
  const text = `${title}\n${body}`
  return /解析失败|\[解析\]|Unsupported URL|Requested format|Unable to download|no such table|Sign in to confirm/i.test(
    text,
  )
}

/** 按错误类别给出具体的自助指引 */
function selfServiceHint(kind?: ParseErrorKind): string {
  switch (kind) {
    case 'authentication':
      return '- **需要登录的内容**：在「设置 → Cookies」配置 Cookie（可自动读取浏览器登录态），然后重新解析。'
    case 'access-denied':
      return '- **403 拒绝访问**：多为访问过于频繁或需要登录。等几分钟重试，或在「设置 → Cookies」配置 Cookie。'
    case 'rate-limit':
      return '- **请求过于频繁**：等几分钟后重试即可。'
    case 'invalid-url':
      return '- **链接无效或不被支持**：请确认链接可直接在浏览器打开。注意部分站点（如微信视频号）目前不在支持范围内，属于已知边界而非缺陷。'
    case 'unsupported-url':
      return '- **该站点不在支持范围**：DownVid 基于 yt-dlp，支持站点见其 supportedsites 列表，属于已知边界而非缺陷。'
    case 'runtime-unavailable':
      return '- **缺少 JS 运行时**：YouTube 解析需要 Node.js 22+ 或 Deno 2.3+，安装后重启应用即可。'
    case 'not-found':
      return '- **视频不存在**：该视频可能已被删除或设为私密，换一个链接试试。'
    default:
      return '- 请参考 README 的常见问题。'
  }
}
